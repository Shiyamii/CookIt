// Tooling (not shipped): compiles the MJML email templates of src/modules/mail/templates/ into
// HTML, with the colors of the web theme (apps/web/src/index.css, light theme). The server only
// fills in the `{{…}}` placeholders of the result: MJML is not needed at runtime.
import { readdir, readFile } from 'node:fs/promises';
import { basename, join } from 'node:path';
import mjml2html from 'mjml';

const ROOT = join(import.meta.dirname, '..', '..', '..');
export const TEMPLATES_DIR = join(ROOT, 'apps/server/src/modules/mail/templates');
export const OUTPUT = join(ROOT, 'apps/server/src/modules/mail/templates.generated.ts');
const THEME = join(ROOT, 'apps/web/src/index.css');

/** The theme tokens an email uses. */
const TOKENS = [
  'foreground',
  'card',
  'muted',
  'muted-foreground',
  'primary',
  'primary-foreground',
  'border',
] as const;

/** `oklch(L C H)` (CSS) to `#rrggbb` (sRGB, clipped). */
export function oklchToHex(value: string): string {
  const match = /oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)/.exec(value);
  if (!match) throw new Error(`Not an oklch() color: ${value}`);
  const [l, c, h] = [Number(match[1]), Number(match[2]), (Number(match[3]) * Math.PI) / 180];
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  return `#${linear
    .map((channel) => {
      const x = Math.min(1, Math.max(0, channel));
      const srgb = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
      return Math.round(srgb * 255)
        .toString(16)
        .padStart(2, '0');
    })
    .join('')}`;
}

/** The light theme's colors (`:root`) and radius, as email clients understand them. */
export async function themeValues(): Promise<Record<string, string>> {
  const css = await readFile(THEME, 'utf8');
  const root = /:root\s*\{([^}]*)\}/.exec(css.replace(/\/\*[\s\S]*?\*\//g, ''))?.[1] ?? '';
  const read = (name: string) => new RegExp(`--${name}:\\s*([^;]+);`).exec(root)?.[1]?.trim();
  const values: Record<string, string> = {};
  for (const token of TOKENS) {
    const value = read(token);
    if (!value) throw new Error(`--${token} not found in ${THEME}`);
    values[token] = oklchToHex(value);
  }
  const radius = Number(/^([\d.]+)rem$/.exec(read('radius') ?? '')?.[1] ?? 1);
  values.radius = `${Math.round(radius * 16)}px`;
  return values;
}

/** Every template, compiled: `{ action: '<!doctype html>…' }`. */
export async function compileTemplates(): Promise<Record<string, string>> {
  const theme = await themeValues();
  const files = (await readdir(TEMPLATES_DIR)).filter((file) => file.endsWith('.mjml')).sort();
  const templates: Record<string, string> = {};
  for (const file of files) {
    const source = (await readFile(join(TEMPLATES_DIR, file), 'utf8'))
      // The template's own explanations stay out of the emails.
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/%%([a-z-]+)%%/g, (_, name: string) => {
        const value = theme[name];
        if (!value) throw new Error(`Unknown theme value %%${name}%% in ${file}`);
        return value;
      });
    const result = await mjml2html(source, { validationLevel: 'strict', minify: false });
    templates[basename(file, '.mjml')] = result.html;
  }
  return templates;
}

/** The generated module. */
export function generatedSource(templates: Record<string, string>): string {
  return [
    '// Generated by `bun run emails` from templates/*.mjml and the web theme. Do not edit.',
    '',
    `export const TEMPLATES = ${JSON.stringify(templates, null, 2)} as const;`,
    '',
    'export type TemplateName = keyof typeof TEMPLATES;',
    '',
  ].join('\n');
}
